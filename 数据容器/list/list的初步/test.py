l = [1, 2, 3, 4, "hello", "world", 3.14, 2.222]
print(l[0])  # 正向索引（从左往右）的顺序中第一个元素的下标为0
print(l[-1])  # 反向索引（从右往左）的顺序中最右边的元素的下标为-1，再往左依次递减
print(l)
del l[1]  # 删除l中的第二个元素
l[1] = 2  # 更改l中的元素
for i in l:
    print(i, end=" ")
print()

# 列表的切片：[开始位置（默认为0）:结束位置（不包含）（默认为列表长度）:步长（默认为1）]
l2 = [23, 12, 55, "hello", "world", 3.14, 1.111]
print(l2[:5:])
